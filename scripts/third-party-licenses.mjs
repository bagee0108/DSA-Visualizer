/**
 * Writes public/THIRD_PARTY_LICENSES.txt: the licence of every package that
 * ships in the production bundle, taken from package-lock.json (everything
 * not marked dev) and each package's own LICENSE file in node_modules.
 *
 *   node scripts/third-party-licenses.mjs           regenerate
 *   node scripts/third-party-licenses.mjs --check   fail if the file is stale
 *
 * Run it after any change to "dependencies" and commit the result. It needs
 * `npm ci` first and no packages of its own.
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public', 'THIRD_PARTY_LICENSES.txt');
const RULE = '='.repeat(72);

const lock = JSON.parse(readFileSync(join(ROOT, 'package-lock.json'), 'utf8'));

function text(path) {
  return readFileSync(path, 'utf8').replace(/\r\n?/g, '\n').trim();
}

/** The first file in a package directory whose name starts with one of these. */
function find(dir, prefixes) {
  const name = readdirSync(dir).find((file) => prefixes.some((prefix) => file.toUpperCase().startsWith(prefix)));
  return name === undefined ? undefined : join(dir, name);
}

const packages = Object.entries(lock.packages)
  .filter(([path, entry]) => path !== '' && entry.dev !== true && entry.devOptional !== true)
  .map(([path, entry]) => {
    const dir = join(ROOT, path);
    if (!existsSync(dir)) throw new Error(`${path} is not installed; run npm ci first`);
    const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const licenseFile = find(dir, ['LICENSE', 'LICENCE', 'COPYING']);
    if (licenseFile === undefined) throw new Error(`${manifest.name} ships no licence file`);
    const noticeFile = find(dir, ['NOTICE']);
    return {
      name: manifest.name,
      version: manifest.version,
      license: manifest.license ?? entry.license ?? 'UNKNOWN',
      homepage: manifest.homepage ?? manifest.repository?.url ?? manifest.repository ?? '',
      licenseText: text(licenseFile),
      notice: noticeFile === undefined ? undefined : text(noticeFile),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

/**
 * Apache-2.0 section 4(d) asks for a package's NOTICE to travel with it. When
 * there is no NOTICE file, the copyright and licence notice the package
 * itself carries (the appendix after the terms) is reproduced instead.
 */
function apacheNotice(pkg) {
  if (pkg.notice !== undefined) return pkg.notice;
  const appendix = pkg.licenseText.split('END OF TERMS AND CONDITIONS')[1]?.trim();
  return `(${pkg.name} ships no NOTICE file. Its own copyright and licence notice:)\n\n${appendix ?? `Licensed under ${pkg.license}.`}`;
}

const apache = packages.filter((pkg) => /Apache-2\.0/.test(pkg.license));

const out = [
  'Lowlink: third-party licences',
  '',
  'Lowlink itself is MIT licensed; see /LICENSE in the source repository.',
  'The production bundle includes the packages below. Each is listed with',
  'its licence, followed by the full licence text it ships with.',
  '',
  'The three fonts are under the SIL Open Font License 1.1; each folder in',
  '/fonts/ holds its OFL.txt with the copyright notice.',
  '',
  'Generated by scripts/third-party-licenses.mjs from package-lock.json.',
  '',
  RULE,
  'Packages',
  RULE,
  '',
  ...packages.map((pkg) => `${pkg.name}@${pkg.version}  ${pkg.license}`),
  '',
  ...(apache.length === 0
    ? []
    : [RULE, 'Notices (Apache-2.0)', RULE, '', ...apache.flatMap((pkg) => [`${pkg.name}@${pkg.version}`, '', apacheNotice(pkg), ''])]),
  ...packages.flatMap((pkg) => [
    RULE,
    `${pkg.name}@${pkg.version}  ${pkg.license}`,
    ...(pkg.homepage === '' ? [] : [String(pkg.homepage)]),
    RULE,
    '',
    pkg.licenseText,
    '',
    ...(pkg.notice === undefined ? [] : ['NOTICE', '', pkg.notice, '']),
  ]),
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== out) {
    console.error('public/THIRD_PARTY_LICENSES.txt is stale; run node scripts/third-party-licenses.mjs');
    process.exit(1);
  }
  console.log(`THIRD_PARTY_LICENSES.txt is current (${packages.length} packages)`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote public/THIRD_PARTY_LICENSES.txt (${packages.length} packages: ${packages.map((pkg) => pkg.name).join(', ')})`);
}
