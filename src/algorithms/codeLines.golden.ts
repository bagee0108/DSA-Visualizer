/**
 * Every frame's code line, for every level, recorded from the levels as they
 * were while frames still carried a JS line number (before they named a step).
 * codeLines.test.ts holds the levels to these: mapping each frame's step
 * through the JS code panel's map has to give back exactly the line it had.
 */

import type { ParamMap, RegisteredAlgorithm } from '../core/define';
import { makeRng } from '../core/random';
import type { Frame } from '../core/types';
import { hash53 } from './graphs/graphTestkit';

export interface CodeLineCase {
  readonly name: string;
  readonly params: ParamMap;
}

/**
 * The default run; each option of every select field, the rest at defaults;
 * and every preset at the smallest, the default and the largest size.
 */
export function codeLineCases(algorithm: RegisteredAlgorithm): CodeLineCase[] {
  const cases: CodeLineCase[] = [{ name: 'default', params: {} }];
  for (const field of algorithm.fields) {
    if (field.kind !== 'select') continue;
    for (const option of field.options ?? []) cases.push({ name: `${field.key}=${option.value}`, params: { [field.key]: option.value } });
  }
  const { min, max } = algorithm.sizeRange;
  const sizes = [...new Set([min, Math.min(max, Math.max(min, algorithm.sizeOf(algorithm.defaults))), max])];
  for (const preset of algorithm.presets) {
    for (const size of sizes) {
      cases.push({ name: `${preset.id}@${size}`, params: preset.build(size, makeRng(size * 31 + preset.id.length)) });
    }
  }
  return cases;
}

/**
 * A run's code lines as one fingerprint: the frame count, then each frame's
 * line followed by the lines its call-stack entries point at ("-" for none).
 */
export function lineTrace(
  frames: readonly Frame[],
  frameLine: (frame: Frame) => number,
  callLine: (entry: Frame['callStack'][number]) => number | undefined,
): string {
  const parts = frames.map((frame) =>
    frame.callStack.length === 0 ? String(frameLine(frame)) : `${frameLine(frame)}[${frame.callStack.map((entry) => callLine(entry) ?? '-').join(' ')}]`,
  );
  return `${frames.length}:${hash53(parts.join(','))}`;
}

