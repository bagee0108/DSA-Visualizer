import type { ParamMap } from '../../core/define';
import { unionFind } from './unionFind';

export const GOLDEN_SIZES = [4, 5, 12, 40, 97, 150] as const;

/** Every preset at every golden size, under each union and compression mode, plus a couple of finds; and the default run. */
export function unionFindCases(makeRng: (seed: number) => () => number): [string, ParamMap][] {
  const cases: [string, ParamMap][] = [['default', {}]];
  for (const preset of unionFind.presets) {
    for (const size of GOLDEN_SIZES) {
      const built = preset.build(size, makeRng(size * 31 + preset.id.length));
      // A capped preset (the ring) may build fewer nodes than asked.
      const nodes = unionFind.sizeOf(built);
      for (const rank of ['1', '0']) {
        for (const compress of ['1', '0']) {
          cases.push([`${preset.id}@${size} r${rank}c${compress}`, { ...built, rank, compress, finds: built.finds ?? `${nodes - 1},${Math.floor(nodes / 2)}` }]);
        }
      }
    }
  }
  return cases;
}

